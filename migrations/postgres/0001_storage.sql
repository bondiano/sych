-- Final storage schema equivalent to SQLite migrations 0001–0010.
-- JSON and domain ids remain TEXT; times, money, counters and flags are BIGINT.

CREATE TABLE repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    connection_id TEXT NOT NULL,
    provider_instance TEXT NOT NULL,
    external_id TEXT NOT NULL,
    full_name TEXT NOT NULL,
    installation_id BIGINT,
    capabilities TEXT,
    capabilities_at BIGINT,
    UNIQUE (tenant_id, connection_id, provider_instance, external_id)
);

CREATE TABLE changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    access_scope TEXT NOT NULL,
    change_key TEXT NOT NULL,
    desired_generation BIGINT NOT NULL,
    repository_id BIGINT REFERENCES repositories (id),
    external_number BIGINT,
    scm_state TEXT,
    head_sha TEXT,
    base_sha TEXT,
    base_ref TEXT,
    fork BIGINT NOT NULL DEFAULT 0,
    synced_at BIGINT,
    UNIQUE (tenant_id, access_scope, change_key)
);

CREATE TABLE runs (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    access_scope TEXT NOT NULL,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    generation BIGINT NOT NULL,
    parent_run_id TEXT,
    inputs TEXT,
    inputs_digest TEXT,
    source_snapshot_id TEXT,
    policy_snapshot_id TEXT,
    state TEXT NOT NULL,
    stage TEXT NOT NULL,
    evidence_deadline BIGINT,
    expected_sources TEXT,
    result_id TEXT,
    result_sha256 TEXT,
    model_attempts BIGINT NOT NULL DEFAULT 0,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    cost_known_micro_usd BIGINT NOT NULL DEFAULT 0,
    unknown_cost_attempts BIGINT NOT NULL DEFAULT 0,
    failure TEXT,
    created_at BIGINT NOT NULL,
    finished_at BIGINT,
    lineage_applied BIGINT NOT NULL DEFAULT 0,
    coverage TEXT,
    unknown_obligations BIGINT,
    UNIQUE (change_id, generation),
    CHECK (state <> 'COMPLETED' OR (result_sha256 IS NOT NULL AND result_id IS NOT NULL))
);

CREATE INDEX runs_by_change ON runs (change_id, generation);

CREATE TABLE artifacts (
    tenant_id TEXT NOT NULL,
    access_scope TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    kind TEXT NOT NULL,
    schema_version BIGINT NOT NULL,
    store_key TEXT NOT NULL,
    size BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    retain_until BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, access_scope, sha256)
);

CREATE TABLE run_artifacts (
    run_id TEXT NOT NULL REFERENCES runs (id),
    role TEXT NOT NULL,
    tenant_id TEXT NOT NULL,
    access_scope TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    PRIMARY KEY (run_id, role)
);

CREATE INDEX run_artifacts_by_artifact ON run_artifacts (tenant_id, access_scope, sha256);
CREATE INDEX artifacts_by_retention ON artifacts (retain_until);

CREATE TABLE model_attempts (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    run_id TEXT NOT NULL REFERENCES runs (id),
    purpose TEXT NOT NULL,
    kind TEXT NOT NULL,
    template TEXT NOT NULL,
    profile TEXT NOT NULL,
    provider TEXT NOT NULL,
    requested_model TEXT NOT NULL,
    resolved_model TEXT,
    generation_id TEXT,
    billing_kind TEXT NOT NULL,
    enforcement TEXT NOT NULL,
    day TEXT NOT NULL,
    month TEXT NOT NULL,
    reserved_micro_usd BIGINT NOT NULL,
    input_tokens_bound BIGINT NOT NULL,
    output_tokens_bound BIGINT,
    state TEXT NOT NULL CHECK (state IN ('RESERVED', 'SETTLED', 'UNKNOWN', 'RELEASED')),
    charge_micro_usd BIGINT,
    reference_micro_usd BIGINT,
    input_tokens BIGINT,
    output_tokens BIGINT,
    reasoning_tokens BIGINT,
    billing_mismatch BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    settled_at BIGINT,
    scope TEXT
);

CREATE INDEX model_attempts_by_run ON model_attempts (run_id);
CREATE INDEX model_attempts_by_period ON model_attempts (tenant_id, month, day);

CREATE TABLE subscription_fees (
    tenant_id TEXT NOT NULL,
    provider TEXT NOT NULL,
    month TEXT NOT NULL,
    amount_micro_usd BIGINT NOT NULL,
    allocated_micro_usd BIGINT NOT NULL,
    recorded_at BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, provider, month)
);

CREATE TABLE inbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_instance TEXT NOT NULL,
    connection_id TEXT NOT NULL,
    delivery_id TEXT NOT NULL,
    event TEXT NOT NULL,
    action TEXT,
    payload_sha256 TEXT NOT NULL,
    normalized TEXT NOT NULL,
    received_at BIGINT NOT NULL,
    decision TEXT NOT NULL,
    UNIQUE (provider_instance, connection_id, delivery_id)
);

CREATE TABLE change_intents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    kind TEXT NOT NULL,
    due_at BIGINT NOT NULL,
    latest_at BIGINT NOT NULL,
    events BIGINT NOT NULL,
    first_inbox_id BIGINT NOT NULL REFERENCES inbox_events (id),
    last_inbox_id BIGINT NOT NULL REFERENCES inbox_events (id),
    created_at BIGINT NOT NULL,
    consumed_at BIGINT,
    CHECK (due_at <= latest_at)
);

CREATE UNIQUE INDEX change_intents_open ON change_intents (change_id, kind)
    WHERE consumed_at IS NULL;
CREATE INDEX change_intents_due ON change_intents (due_at) WHERE consumed_at IS NULL;

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES runs (id),
    kind TEXT NOT NULL,
    task_key TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('QUEUED', 'CLAIMED', 'DONE', 'FAILED', 'CANCELLED')),
    owner TEXT,
    lease_epoch BIGINT NOT NULL DEFAULT 0,
    lease_until BIGINT,
    deadline BIGINT NOT NULL,
    attempts BIGINT NOT NULL DEFAULT 0,
    max_attempts BIGINT NOT NULL,
    next_attempt_at BIGINT NOT NULL,
    last_error TEXT,
    created_at BIGINT NOT NULL,
    finished_at BIGINT,
    UNIQUE (run_id, kind, task_key)
);

CREATE INDEX jobs_ready ON jobs (state, next_attempt_at);

CREATE TABLE change_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    run_id TEXT,
    kind TEXT NOT NULL,
    detail TEXT NOT NULL,
    at BIGINT NOT NULL
);

CREATE INDEX change_events_by_change ON change_events (change_id, id);

CREATE TABLE publication_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    slot TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('SUMMARY', 'INLINE', 'CHECK')),
    marker TEXT NOT NULL,
    remote_id TEXT,
    desired_generation BIGINT NOT NULL,
    desired_result_id TEXT NOT NULL,
    observed_generation BIGINT,
    observed_body_sha256 TEXT,
    relevance TEXT NOT NULL DEFAULT 'CURRENT' CHECK (relevance IN ('CURRENT', 'STALE')),
    updated_at BIGINT NOT NULL,
    fingerprint TEXT,
    anchor TEXT,
    UNIQUE (change_id, slot)
);

CREATE TABLE publication_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id BIGINT NOT NULL REFERENCES publication_objects (id),
    run_id TEXT NOT NULL REFERENCES runs (id),
    result_id TEXT NOT NULL,
    generation BIGINT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('PENDING', 'PUBLISHING', 'DELIVERED', 'UNCERTAIN',
        'FAILED', 'CANCELLED', 'SUPERSEDED')),
    attempt_id TEXT,
    request_digest TEXT,
    body TEXT,
    attempts BIGINT NOT NULL DEFAULT 0,
    owner TEXT,
    lease_epoch BIGINT NOT NULL DEFAULT 0,
    lease_until BIGINT,
    remote_id TEXT,
    last_response TEXT,
    last_error TEXT,
    reconcile_deadline BIGINT,
    next_action_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    finished_at BIGINT,
    UNIQUE (object_id, generation)
);

CREATE INDEX publication_operations_ready ON publication_operations (state, next_action_at);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    correlation_id TEXT NOT NULL,
    metadata TEXT NOT NULL,
    at BIGINT NOT NULL
);

CREATE INDEX audit_events_by_tenant ON audit_events (tenant_id, at);

CREATE TABLE findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    fingerprint TEXT NOT NULL,
    finding_id TEXT NOT NULL,
    category TEXT NOT NULL,
    rule_id TEXT,
    path TEXT,
    state TEXT NOT NULL CHECK (state IN ('OPEN', 'RESOLVED', 'DISMISSED', 'OBSOLETE')),
    first_run_id TEXT NOT NULL,
    last_run_id TEXT NOT NULL,
    predecessor_id BIGINT REFERENCES findings (id),
    updated_at BIGINT NOT NULL,
    UNIQUE (change_id, fingerprint)
);

CREATE TABLE finding_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES findings (id),
    run_id TEXT,
    from_state TEXT,
    to_state TEXT NOT NULL,
    reason TEXT NOT NULL,
    actor TEXT,
    evidence TEXT NOT NULL DEFAULT '[]',
    at BIGINT NOT NULL
);

CREATE INDEX finding_events_by_finding ON finding_events (finding_id, id);

CREATE TABLE feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    change_id BIGINT NOT NULL REFERENCES changes (id),
    finding_id BIGINT NOT NULL REFERENCES findings (id),
    actor TEXT NOT NULL,
    judgement TEXT NOT NULL CHECK (judgement IN ('USEFUL', 'NOT_USEFUL', 'FALSE_POSITIVE', 'WONT_FIX')),
    scope TEXT NOT NULL,
    rationale TEXT NOT NULL,
    policy_snapshot_id TEXT,
    at BIGINT NOT NULL
);

CREATE TABLE waivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    repository_id BIGINT NOT NULL REFERENCES repositories (id),
    rule_id TEXT NOT NULL,
    paths TEXT NOT NULL,
    reason TEXT NOT NULL,
    owner TEXT NOT NULL,
    author TEXT NOT NULL,
    expires_at BIGINT,
    until TEXT,
    policy_snapshot_id TEXT,
    created_at BIGINT NOT NULL,
    revoked_at BIGINT,
    CHECK (expires_at IS NOT NULL OR until IS NOT NULL)
);

CREATE TABLE idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    actor TEXT NOT NULL,
    endpoint TEXT NOT NULL,
    key TEXT NOT NULL,
    body_sha256 TEXT NOT NULL,
    response_status BIGINT,
    response_body TEXT,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    UNIQUE (tenant_id, actor, endpoint, key)
);

CREATE TABLE tour_sessions (
    tenant_id TEXT NOT NULL,
    tour_id TEXT NOT NULL,
    actor TEXT NOT NULL,
    run_id TEXT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('IN_PROGRESS', 'COMPLETED', 'DISMISSED')),
    revealed TEXT NOT NULL DEFAULT '[]',
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, tour_id, actor)
);

CREATE TABLE tour_exchanges (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    tour_id TEXT NOT NULL,
    actor TEXT NOT NULL,
    run_id TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX tour_exchanges_session ON tour_exchanges (tenant_id, tour_id, actor, created_at);
