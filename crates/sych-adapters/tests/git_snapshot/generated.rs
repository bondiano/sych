//! Which changed files count as generated: the target tip's attributes and markers its own
//! version already carried are trusted; a marker the change writes is only its claim.

use super::{capture, commit, git, path, repo, write};

#[test]
fn linguist_generated_comes_from_the_target_tip_only() {
    let dir = repo();
    let d = dir.path();
    write(
        d,
        ".gitattributes",
        b"data/*.json linguist-generated=true\n",
    );
    commit(d, "base");
    git(d, &["checkout", "-q", "-b", "feature"]);
    write(
        d,
        ".gitattributes",
        b"data/*.json linguist-generated=true\nsrc/*.rs linguist-generated\n",
    );
    write(d, "data/report.json", b"{}\n");
    write(d, "src/lib.rs", b"pub fn hidden() {}\n");
    commit(d, "feature");
    let snap = capture(d, "main", "feature", None).expect("snapshot");
    let generated = |p: &str| {
        snap.manifest
            .files
            .iter()
            .find(|f| f.new.as_ref().is_some_and(|s| s.path == path(p)))
            .expect(p)
            .generated
    };
    assert!(generated("data/report.json"));
    assert!(
        !generated("src/lib.rs"),
        "the change's own attributes are not trusted"
    );
}

#[test]
fn a_marker_counts_when_the_target_already_carried_it() {
    let dir = repo();
    let d = dir.path();
    write(
        d,
        "gen/api.rs",
        b"// @generated by fixture\npub struct Api;\n",
    );
    write(d, "src/lib.rs", b"pub fn shown() {}\n");
    commit(d, "base");
    git(d, &["checkout", "-q", "-b", "feature"]);
    write(
        d,
        "gen/api.rs",
        b"// @generated by fixture\npub struct Api(u8);\n",
    );
    write(
        d,
        "src/lib.rs",
        b"// @generated, says the author\npub fn hidden() {}\n",
    );
    commit(d, "feature");
    let snap = capture(d, "main", "feature", None).expect("snapshot");
    let file = |p: &str| {
        snap.manifest
            .files
            .iter()
            .find(|f| f.new.as_ref().is_some_and(|s| s.path == path(p)))
            .expect(p)
            .clone()
    };
    let regenerated = file("gen/api.rs");
    assert!(regenerated.generated && !regenerated.generated_claim);
    let claimed = file("src/lib.rs");
    assert!(
        !claimed.generated && claimed.generated_claim,
        "a marker added by the change is the author's word"
    );
}

#[test]
fn the_target_attributes_make_a_claimed_file_trusted_generated() {
    let dir = repo();
    let d = dir.path();
    write(d, ".gitattributes", b"gen/*.rs linguist-generated=true\n");
    commit(d, "base");
    git(d, &["checkout", "-q", "-b", "feature"]);
    write(
        d,
        "gen/api.rs",
        b"// @generated by fixture\npub struct Api;\n",
    );
    commit(d, "feature");
    let snap = capture(d, "main", "feature", None).expect("snapshot");
    let file = snap
        .manifest
        .files
        .iter()
        .find(|f| f.new.as_ref().is_some_and(|s| s.path == path("gen/api.rs")))
        .expect("gen/api.rs");
    assert!(file.generated && !file.generated_claim);
}
